"""# **Campo de Filtro Específico: Ônibus com Velocidade Abaixo de 20 km/h (Possível Ofensor de Atrasos)**"""

analise_regional = (
    df_etl
    .groupBy("regiao")
    .agg(
        F.round(F.avg("velocidade_kmh"), 2).alias("velocidade_media_kmh"),
        F.count("*").alias("quantidade_registros"),
        F.round(F.avg("latitude"), 5).alias("latitude_media"),
        F.round(F.avg("longitude"), 5).alias("longitude_media")
    )
    .orderBy("velocidade_media_kmh")
)

limite_velocidade = 20.0

gargalos = (
    analise_regional
    .withColumn(
        "classificacao",
        F.when(
            F.col("velocidade_media_kmh") < limite_velocidade,
            "Possível gargalo"
        ).otherwise("Fluxo menos lento")
    )
)

gargalos.show(truncate=False)

